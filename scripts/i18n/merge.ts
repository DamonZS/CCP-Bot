/**
 * Folds the translated chunks into `app/src/lib/i18n/messages/zh-CN.ts`.
 *
 *   bun scripts/i18n/merge.ts
 *
 * The merged file is sorted by source string so that a diff after re-running the codemod shows only
 * the strings that actually changed. Entries already in the module are kept: some of them are
 * written by hand (error copy the codemod never sees) and re-running this must not drop them.
 *
 * It exits non-zero and lists the gap when a string the codemod wrapped has no translation, because
 * a missing key means that piece of the interface silently stays English.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";

const CHUNK_DIR = "scripts/i18n/chunks";
const TARGET = "app/src/lib/i18n/messages/zh-CN.ts";

/** Reads the object literal currently exported as ZH_CN, so hand-written entries survive a merge. */
function readExisting(): Map<string, string> {
  const text = readFileSync(TARGET, "utf8");
  const source = ts.createSourceFile(
    "zh-CN.ts",
    text,
    ts.ScriptTarget.ESNext,
    true,
    ts.ScriptKind.TS,
  );
  const out = new Map<string, string>();
  const visit = (node: ts.Node) => {
    if (
      ts.isVariableDeclaration(node) &&
      ts.isIdentifier(node.name) &&
      node.name.text === "ZH_CN" &&
      node.initializer &&
      ts.isObjectLiteralExpression(node.initializer)
    ) {
      for (const property of node.initializer.properties) {
        if (
          ts.isPropertyAssignment(property) &&
          ts.isStringLiteral(property.name) &&
          ts.isStringLiteral(property.initializer)
        ) {
          out.set(property.name.text, property.initializer.text);
        }
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  return out;
}

function readChunks(): Map<string, string> {
  const out = new Map<string, string>();
  const files = readdirSync(CHUNK_DIR).filter((name) =>
    name.endsWith(".zh.json"),
  );
  for (const file of files) {
    const map = JSON.parse(
      readFileSync(`${CHUNK_DIR}/${file}`, "utf8"),
    ) as Record<string, string>;
    for (const [key, value] of Object.entries(map)) {
      // An empty value would render as English anyway (see `t`), but it usually means the
      // translator skipped a line, so it is treated as missing rather than as a translation.
      if (typeof value === "string" && value.trim().length > 0) {
        out.set(key, value);
      }
    }
  }
  return out;
}

const existing = readExisting();
const translated = readChunks();
const inventory = JSON.parse(
  readFileSync("scripts/i18n/inventory.json", "utf8"),
) as {
  entries: { source: string; count: number }[];
};

const merged = new Map<string, string>(existing);
for (const [key, value] of translated) {
  merged.set(key, value);
}

const missing = inventory.entries
  .map((entry) => entry.source)
  .filter((source) => !merged.has(source));

const keys = [...merged.keys()].sort((a, b) => a.localeCompare(b, "en"));
const body = keys
  .map(
    (key) =>
      `  ${JSON.stringify(key)}: ${JSON.stringify(merged.get(key) as string)},`,
  )
  .join("\n");

const header = `/**
 * Simplified Chinese copy, keyed by the English string it replaces.
 *
 * The key is the source text, not a name, which is what lets a component say \`t("Save")\` without
 * anybody maintaining a second vocabulary of identifiers. \`t\` falls back to the key when it finds
 * no entry here, so a string missing from this map shows up in English rather than as a broken key.
 *
 * Generated by \`scripts/i18n/merge.ts\` from the codemod inventory and the translated chunks; edit a
 * translation by editing this file, and re-run the merge only after re-running the codemod.
 */
export const ZH_CN: Record<string, string> = {
`;

writeFileSync(TARGET, `${header}${body}\n};\n`);

console.log(
  `${merged.size} entries -> ${TARGET} (${translated.size} from chunks, ${existing.size} already present)`,
);

if (missing.length > 0) {
  console.log(`${missing.length} strings have no translation:`);
  for (const source of missing.slice(0, 40)) {
    console.log(`  ${JSON.stringify(source)}`);
  }
  process.exitCode = 1;
}
